import assert from 'node:assert/strict'
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
const failures=[];page.on('pageerror',e=>failures.push(e.message))
const checks=[]
const check = name => {checks.push(name);console.log('PASS',name)}
try {
 await page.goto('http://127.0.0.1:8443/')
 await page.getByRole('button',{name:'Open STRIDE',exact:true}).click()
 await page.getByText('Demo data · simulated progress').waitFor();check('landing and explicit demo render')
 await page.getByRole('button',{name:'Start Guidance',exact:true}).click()
 await page.getByRole('button',{name:'Confirm Arrival'}).click()
 await page.getByRole('button',{name:'Repeat',exact:true}).click()
 assert.match(await page.locator('.sa-progress').innerText(),/1 \/ 2/);check('preview confirm/repeat deterministic')
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 assert.ok(await page.getByRole('button',{name:'Stop guidance',exact:true}).isVisible());check('Stop reachable across tabs')
 await page.getByLabel('Session ID',{exact:true}).fill('test-session')
 await page.getByLabel('Session token',{exact:true}).fill('test-only-token')
 await page.getByRole('button',{name:'Connect backend',exact:true}).click()
 await page.getByText('Connected to backend session test-session.').waitFor()
 assert.equal(await page.getByLabel('Session token',{exact:true}).inputValue(),'')
 const cookies=await page.context().cookies();assert.ok(cookies.some(c=>c.name==='stride_session'&&c.httpOnly));check('actual FastAPI cookie login through Vite proxy')
 assert.equal(await page.getByText('Demo data · simulated progress').count(),0)
 await page.getByRole('button',{name:'Guidance',exact:true}).click()
 assert.ok(await page.getByRole('button',{name:'Select',exact:true}).isDisabled());check('unchecked backend route disabled; fixtures cleared')
 await page.getByRole('button',{name:'Start Guidance',exact:true}).click()
 await page.getByText('Proceed to checkpoint A.',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Confirm Arrival'}).click()
 await page.getByText('Turn left at checkpoint B.',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Repeat',exact:true}).click()
 assert.match(await page.locator('.sa-progress').innerText(),/1 \/ 3/)
 await page.getByRole('button',{name:'Pause',exact:true}).first().click()
 await page.getByRole('button',{name:'Resume',exact:true}).first().click()
 await page.getByText('Turn left at checkpoint B.',{exact:true}).waitFor();check('actual backend start, confirm, repeat, pause/resume')
 await page.getByRole('button',{name:'Start',exact:true}).click()
 await page.getByRole('button',{name:'Stop awareness',exact:true}).waitFor()
 await page.getByRole('button',{name:'Stop awareness',exact:true}).click()
 await page.getByText('Awareness stopped for this session.').waitFor()
 assert.equal(await page.getByRole('button',{name:'Start',exact:true}).count(),0);check('terminal vision stop cannot restart')
 await page.getByRole('button',{name:'Devices',exact:true}).click()
 await page.getByLabel('Controller ID',{exact:true}).fill('wrong-controller')
 await page.getByRole('button',{name:'Pair controller',exact:true}).click()
 await page.locator('.sa-warning').filter({hasText:/not registered|not configured|denied|Controller|controller/}).first().waitFor();check('pairing errors visible')
 await page.getByLabel('Controller ID',{exact:true}).fill('test-controller')
 await page.getByRole('button',{name:'Pair controller',exact:true}).click()
 await page.getByText('Paired, awaiting contact',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Guidance',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('.sa-route-name')?.textContent?.includes('blocked'))
 assert.ok(await page.getByRole('button',{name:'Confirm Arrival'}).isDisabled());check('unknown paired sensor blocks route and confirmation')
 await page.getByRole('button',{name:'Memory',exact:true}).click()
 await page.getByText('No saved sightings match this search.',{exact:true}).waitFor();check('real memory empty state, no fixture sightings')
 await page.getByRole('button',{name:'Stop guidance',exact:true}).click()
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await page.getByLabel('Session ID',{exact:true}).fill('second-session')
 await page.getByLabel('Session token',{exact:true}).fill('second-test-token')
 await page.getByRole('button',{name:'Reconnect',exact:true}).click()
 await page.getByText('Connected to backend session second-session.').waitFor()
 await page.getByLabel('Text size',{exact:true}).selectOption('largest')
 assert.equal(await page.evaluate(()=>document.documentElement.dataset.strideTextSize),'largest')
 await page.getByRole('button',{name:'Dark',exact:true}).click()
 assert.ok(await page.evaluate(()=>document.documentElement.classList.contains('dark')));check('large text and dark appearance controls work')
 await page.getByRole('button',{name:'Devices',exact:true}).click()
 assert.equal(await page.getByLabel('Controller ID',{exact:true}).inputValue(),'');check('session switching clears old device/navigation')
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));check('390px portrait has no horizontal overflow')
 await page.screenshot({path:'/tmp/stride-dashboard-mobile.png',fullPage:true})
 await page.setViewportSize({width:1440,height:1000})
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));check('desktop reflow without horizontal overflow')
 assert.deepEqual(failures,[]);check('no application JS errors')
 console.log(JSON.stringify({passed:checks.length,checks,browser:browser.version(),mode:'real FastAPI / synthetic routes, no detector or hardware'},null,2))
} finally { await browser.close() }
